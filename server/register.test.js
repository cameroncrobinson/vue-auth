const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { scryptSync } = require('node:crypto')
const { createApp } = require('./index')

async function main() {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'vue-auth-test-'))
  const dataFile = path.join(directory, 'users.json')
  const server = createApp({ dataFile }).listen(0, '127.0.0.1')
  await new Promise(resolve => server.on('listening', resolve))
  const url = `http://127.0.0.1:${server.address().port}/api/register`
  const post = body => fetch(url, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body) })
  try {
    assert.equal((await post({})).status, 400)
    const input = { username: 'Test User', email: 'TEST@example.com', password: 'test-password-123' }
    const response = await post(input)
    assert.equal(response.status, 201)
    const result = await response.json()
    assert.equal(result.user.email, 'test@example.com')
    assert.equal(result.user.passwordHash, undefined)
    assert.equal(result.user.salt, undefined)
    const stored = JSON.parse(fs.readFileSync(dataFile, 'utf8'))[0]
    assert.equal(stored.password, undefined)
    assert.equal(stored.passwordHash, scryptSync(input.password, stored.salt, 64).toString('hex'))
    assert.equal((await post({ ...input, email: 'test@example.com' })).status, 409)
    const concurrent = await Promise.all([post({ ...input, email: 'other@example.com' }), post({ ...input, email: 'OTHER@example.com' })])
    assert.deepEqual(concurrent.map(response => response.status).sort(), [201, 409])
    const malformed = await fetch(url, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: '{' })
    assert.equal(malformed.status, 400)
    assert.equal(JSON.parse(fs.readFileSync(dataFile, 'utf8')).length, 2)
    const base = url.replace('/register', '')
    const login = body => fetch(`${base}/login`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body) })
    assert.equal((await fetch(`${base}/me`)).status, 401)
    assert.equal((await login({})).status, 400)
    assert.equal((await login({ email: input.email, password: 'wrong-password' })).status, 401)
    assert.equal((await login({ email: 'missing@example.com', password: input.password })).status, 401)
    const signedIn = await login({ email: input.email, password: input.password })
    assert.equal(signedIn.status, 200)
    const signedInBody = await signedIn.json()
    assert.deepEqual(Object.keys(signedInBody.user).sort(), ['email', 'id', 'username'])
    const cookieHeader = signedIn.headers.get('set-cookie')
    assert.match(cookieHeader, /HttpOnly/i)
    assert.match(cookieHeader, /SameSite=Strict/i)
    const cookie = cookieHeader.split(';')[0]
    const sessionResponse = await fetch(`${base}/me`, { headers: { Cookie: cookie } })
    assert.equal(sessionResponse.status, 200)
    assert.deepEqual((await sessionResponse.json()).user, signedInBody.user)
    const forged = await fetch(`${base}/me`, { headers: { Cookie: 'vue-auth.sid=forged' } })
    assert.equal(forged.status, 401)
    const logout = await fetch(`${base}/logout`, { method: 'POST', headers: { Cookie: cookie } })
    assert.equal(logout.status, 200)
    assert.equal((await fetch(`${base}/me`, { headers: { Cookie: cookie } })).status, 401)
    console.log('Passed: registration, validation, password hashing, duplicate emails, concurrent duplicates, malformed JSON, persisted records, login, session cookies, protected user data, and logout.')
  } finally {
    await new Promise(resolve => server.close(resolve))
    fs.rmSync(directory, { recursive: true, force: true })
  }
}
main().catch(error => { console.error(error); process.exitCode = 1 })

